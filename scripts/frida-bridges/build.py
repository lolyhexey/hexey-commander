"""Bundle the Frida Java and ObjC bridges into one plain script.

Frida 17 dropped the bridges from its runtime, so hexey_frida.py prepends this
bundle to scripts that use Java or ObjC. Needs `npm ci` here and frida-python.
"""
import json
import os

import frida

here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, "..", "..", "src", "remote-device", "scripts", "frida-bridges.js")

versions = {
    name: json.load(open(os.path.join(here, "node_modules", name, "package.json"), encoding="utf-8"))["version"]
    for name in ("frida-java-bridge", "frida-objc-bridge")
}
bundle = frida.Compiler().build(
    "entry.js", project_root=here, bundle_format="iife",
    type_check="none", source_maps="omitted", compression="terser",
)
header = (
    "// Generated by scripts/frida-bridges/build.py with frida %s; do not edit.\n"
    "// frida-java-bridge %s, frida-objc-bridge %s: LGPL-2.0 WITH WxWindows-exception-3.1\n"
) % (frida.__version__, versions["frida-java-bridge"], versions["frida-objc-bridge"])
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(header + bundle + "\n")
print("wrote %s (%d bytes)" % (os.path.normpath(out_path), len(header) + len(bundle)))
